"""The incident report as Markdown, for the analyst's case notes.

Text that came from logs, a language model or an analyst's note is untrusted: it is escaped
so it cannot add links, images, HTML or headings to the document.
"""

from __future__ import annotations

import re

from agentsoc.api import models as m

_SPECIAL = re.compile(r"([\\`*_{}\[\]()<>#+\-.!|~])")

DECISION_TEXT = {"accepted": "Accepted: confirmed, needs follow-up",
                 "dismissed": "Dismissed", "more_evidence": "More evidence requested",
                 "reopened": "Reopened", "open": "Open: awaiting a decision"}
REASON_TEXT = {"expected_activity": "expected activity", "false_positive": "false positive",
               "duplicate": "duplicate of another incident",
               "authorised_test": "authorised test", "other": "other"}


def esc(value: object) -> str:
    text = " ".join(str(value).split())  # no line breaks: one value stays on one line
    return _SPECIAL.sub(r"\\\1", text)


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    if not rows:
        return ["_None._", ""]
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(esc(c) if c is not None else "—" for c in row) + " |"
            for row in rows]
    return [*out, ""]


def render_markdown(r: m.ReportView) -> str:
    inc = r.incident
    out: list[str] = [f"# Incident report: {esc(inc.incident_id)}", ""]
    out += [f"> {esc(n)}" for n in r.notices] + [""]
    out += _table(["Item", "Value"], [
        ["Data source", r.source_label], ["Dataset", r.dataset_label],
        ["Dataset SHA-256", r.dataset_sha256], ["Detection engine", r.detection_engine],
        ["Generated", r.generated_at.isoformat(timespec="seconds")],
        ["Generated by", r.generated_by]])

    out += ["## Analyst decision", ""]
    out.append(f"**Status:** {esc(DECISION_TEXT[r.review.status])}")
    out.append("")
    out += _table(["When", "Analyst", "Decision", "Reason", "Window", "Note", "This version"], [
        [e.created_at.isoformat(timespec="seconds"), e.analyst, DECISION_TEXT[e.decision],
         REASON_TEXT.get(e.reason or "", None), f"{e.window_hours} h" if e.window_hours else None,
         e.note, "yes" if e.current_version else "no (earlier version)"]
        for e in r.review.history])

    out += ["## Summary", "", esc(inc.description), ""]
    out += _table(["Item", "Value"], [
        ["Principal account", inc.principal_user],
        ["Period", f"{inc.first_seen_label} to {inc.last_seen_label}"],
        ["Detection severity", inc.severity],
        ["Risk", f"{inc.risk_band} {inc.risk_score}" if inc.risk_score is not None
         else r.risk_unavailable],
        ["Accounts", ", ".join(inc.involved_users)], ["Hosts", ", ".join(inc.involved_hosts)],
        ["Evidence events", inc.evidence_count], ["Findings", inc.finding_count]])
    out += ["**Severity rationale:** " + esc(inc.severity_rationale), ""]

    out += ["## Detection findings", ""]
    out += _table(["Finding", "Rule", "Severity", "Description", "Period"], [
        [f.finding_id, f.rule_title, f.severity, f.description,
         f"{f.first_seen_label} to {f.last_seen_label}"] for f in inc.findings])

    out += ["## Timeline", ""]
    out += _table(["Time", "Event", "Account", "From", "To", "Kind", "Outcome", "Rules"], [
        [e.time_label, e.event_id, e.src_user, e.src_host, e.dst_host, e.orientation,
         e.outcome, ", ".join(e.cited_by)] for e in inc.timeline])
    if inc.missing_evidence_ids:
        out += [f"**Missing evidence:** {len(inc.missing_evidence_ids)} cited event(s) were not "
                "found in the verified dataset.", ""]

    out += ["## Attack paths (structural assessment)", ""]
    if r.paths_unavailable:
        out += [esc(r.paths_unavailable), ""]
    else:
        out += _table(["Path", "Kind", "Verdict", "Hosts", "Reasons"], [
            [p.path_id, p.kind, p.verdict, " → ".join(p.hosts), "; ".join(p.reasons)]
            for p in r.paths])

    out += ["## Risk and proposed response", ""]
    if r.risk is None:
        out += [esc(r.risk_unavailable or "Not available."), ""]
    else:
        rec = r.risk.record
        out += [f"**Risk score:** {rec.risk.score:.1f} ({esc(rec.risk.band.value)}). "
                f"**Investigation confidence:** {rec.confidence.score:.1f} "
                f"({esc(rec.confidence.level.value)}).", ""]
        out += ["Proposed actions (dry-run, not executed):", ""]
        out += _table(["Action", "Target", "Needs approval", "Rationale"], [
            [a.action_type.value, a.target, "yes" if a.requires_approval else "no", a.rationale]
            for a in rec.actions])

    out += ["## Investigation", ""]
    inv = r.investigation
    if inv is None:
        out += ["_No investigation has been run._", ""]
    else:
        c = inv.conclusion
        engine = "language model" if inv.diagnostics.engine == "llm" else "deterministic analysis"
        out += [f"_Produced by {engine}; its text is untrusted and shown escaped._", "",
                f"**Most plausible:** {esc(c.most_plausible_title)} "
                f"(confidence {c.confidence:.2f})", "", esc(c.summary), "",
                f"**Uncertainty:** {esc(c.uncertainty)}", ""]
        out += _table(["Hypothesis", "Kind", "Confidence", "Narrative"], [
            [h.title, h.kind, f"{h.confidence:.2f}", h.narrative] for h in inv.hypotheses])
        if c.next_steps:
            out += ["**Suggested next steps:**", ""] + [f"- {esc(s)}" for s in c.next_steps]
            out.append("")

    if r.agents is not None:
        a = r.agents
        mode = (f"expanded to ±{a.window_hours} h at the analyst's request"
                if a.mode == "expanded" else "standard")
        out += [f"## Specialised agents ({mode})", "", esc(a.correlation.summary), ""]
        if a.correlation.corroborated:
            out += ["**Corroborated by more than one agent:**", ""]
            out += [f"- {esc(x)}" for x in a.correlation.corroborated] + [""]
        if a.correlation.conflicts:
            out += ["**Agents disagree:**", ""] + [f"- {esc(x)}" for x in a.correlation.conflicts]
            out.append("")
        for agent in a.agents:
            out += [f"### {esc(agent.title)} ({esc(agent.status)})", ""]
            out += [f"- {esc(f.stance)}, {esc(f.strength)}: {esc(f.statement)}"
                    + (" _(wider window)_" if f.expanded else "") for f in agent.findings]
            out += [f"- not available: {esc(g)}" for g in agent.gaps] + [""]

    plan = r.agents.response_plan if r.agents is not None else None
    if plan is not None:
        out += ["## How to stop this (recommended response)", "", esc(plan.summary), ""]
        for phase, heading in (("contain", "Contain"), ("investigate", "Investigate"),
                               ("recover", "Recover"), ("prevent", "Prevent")):
            steps = [s for s in plan.steps if s.phase == phase]
            if steps:
                out += [f"### {heading}", ""]
                out += [f"{i}. {esc(s.action)}"
                        + (" **(disruptive: needs approval)**" if s.disruptive else "")
                        + f" _Why:_ {esc(s.why)}"
                        + (" _Also proposed by the risk engine._" if s.risk_engine_proposed
                           else "")
                        for i, s in enumerate(steps, 1)] + [""]
        out += [f"- {esc(n)}" for n in plan.notes] + [""]

    if r.context is not None:
        ctx = r.context
        out += [f"## Wider context ({ctx.window_hours} h either side)", ""]
        out += [f"- {esc(o)}" for o in ctx.observations] + [""]
        out += _table(["Host pair", "Seen before", "First seen", "Seen after"], [
            [f"{p.src_host} → {p.dst_host}", p.before, p.first_seen_label, p.after]
            for p in ctx.pairs])
        out += _table(["Related incident", "Account", "Severity", "Relation", "Status"], [
            [x.incident_id, x.principal_user, x.severity, x.relation,
             DECISION_TEXT[x.review_status]] for x in ctx.related])
        out += [f"- {esc(x)}" for x in ctx.limitations] + [""]

    out += ["## Limitations and missing information", ""]
    out += [f"- {esc(x)}" for x in [*inc.limitations, *inc.missing_information]] + [""]
    out += ["## Possible benign explanations", ""]
    out += [f"- {esc(x)}" for x in inc.benign_explanations] + [""]
    return "\n".join(out)
